#!/usr/bin/env python3
"""Insert, update, or remove the WeRead entry in an EmulationStation gamelist."""
from pathlib import Path
import argparse
import os
import re
import tempfile
from xml.etree import ElementTree as ET


PATH_VALUES = {"./Weread.sh", "Weread.sh"}

# The <game> element tags we manage, in the order the fragment lists them.
ENTRY_TAGS = ("path", "name", "desc", "image", "genre")


def _entry_values(fragment_bytes):
    root = ET.fromstring(fragment_bytes)
    if root.tag != "game":
        raise ValueError("fragment root must be <game>")
    values = {child.tag: child.text or "" for child in root}
    required = {"path", "name", "desc", "image"}
    missing = required.difference(values)
    if missing:
        raise ValueError("fragment missing: " + ", ".join(sorted(missing)))
    return values


def _write_empty_tag(parent, tag, value):
    child = ET.SubElement(parent, tag)
    child.text = value
    return child


def _find_entry(root):
    for game in root.findall("game"):
        if (game.findtext("path") or "").strip() in PATH_VALUES:
            return game
    return None


def _replace_entry(root, values):
    """Update the WeRead <game> in place, preserving its comments.

    The document is parsed with a parser that keeps comments as real nodes.
    ElementTree drops them otherwise, so a plain parse/rewrite silently erased
    every hand-written comment in the user's gamelist on each install.
    """
    old = _find_entry(root)
    if old is None:
        # Append after the last <game>, which keeps any trailing comment that
        # documents the end of a curated block at the end of the file.
        last_game = root.findall("game")
        index = len(list(root)) if not last_game else list(root).index(last_game[-1]) + 1
        old = ET.Element("game")
        root.insert(index, old)
    # Replace each managed tag with a fresh element so the child order matches
    # the fragment, while any tag we do not manage stays where the user put it.
    for child in list(old):
        if child.tag in ENTRY_TAGS:
            old.remove(child)
    for tag in ENTRY_TAGS:
        if tag in values:
            _write_empty_tag(old, tag, values[tag])
    return old


def _prolog(xml_bytes):
    """The text between the XML declaration and the root element.

    Comments that sit before <gameList> are not part of the element tree, so the
    parser cannot hand them back and a plain rewrite would drop them. Keep the
    prolog verbatim and re-attach it after serialising.
    """
    text = xml_bytes.lstrip()
    if text.startswith(b"<?xml"):
        end = text.find(b"?>")
        if end < 0:
            return b""
        text = text[end + 2:].lstrip()
    start = text.find(b"<gameList")
    if start < 0:
        return b""
    prolog = text[:start]
    # Only keep actual content; whitespace between the declaration and root is
    # regenerated by the serialiser anyway.
    if not prolog.replace(b"\r", b"").replace(b"\n", b"").strip():
        return b""
    return prolog.rstrip(b"\r\n") + b"\n"


def _join_prolog(prolog, body):
    if not prolog:
        return body
    # The serialiser emits the declaration first, so insert after it.
    if body.startswith(b"<?xml") and body.find(b"?>") > 0:
        cut = body.find(b"?>") + 2
        while cut < len(body) and body[cut:cut + 1] in (b"\r", b"\n"):
            cut += 1
        return body[:cut] + prolog + b"\n" + body[cut:]
    return prolog + b"\n" + body


def remove_weread(xml_bytes):
    root = _parse(xml_bytes)
    old = _find_entry(root)
    if old is not None:
        root.remove(old)
    return _join_prolog(_prolog(xml_bytes), _serialize(root))


def _parse(xml_bytes):
    return ET.fromstring(xml_bytes, parser=_comment_parser())


def _comment_parser():
    # insert_comments makes comments real nodes in the tree, so they survive the
    # rewrite instead of being dropped by the parser.
    return ET.XMLParser(target=ET.TreeBuilder(insert_comments=True))


def _serialize(root):
    try:
        ET.indent(root, space="  ")
    except AttributeError:
        pass
    return ET.tostring(root, encoding="utf-8", xml_declaration=True) + b"\n"


def upsert_weread(xml_bytes, fragment_bytes=None):
    if fragment_bytes is None:
        fragment_path = Path(__file__).with_name("gamelist.fragment.xml")
        fragment_bytes = fragment_path.read_bytes()
    root = _parse(xml_bytes)
    if root.tag != "gameList":
        raise ValueError("gamelist root must be <gameList>")
    _replace_entry(root, _entry_values(fragment_bytes))
    return _join_prolog(_prolog(xml_bytes), _serialize(root))


def _atomic_write(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=path.name + ".", dir=str(path.parent))
    try:
        with os.fdopen(descriptor, "wb") as target:
            target.write(data)
            target.flush()
            os.fsync(target.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("gamelist", type=Path)
    parser.add_argument("--fragment", type=Path)
    parser.add_argument("--remove", action="store_true")
    args = parser.parse_args()
    source = args.gamelist.read_bytes() if args.gamelist.exists() else b"<?xml version='1.0'?><gameList/>"
    if args.remove:
        result = remove_weread(source)
    else:
        fragment = args.fragment.read_bytes() if args.fragment else None
        result = upsert_weread(source, fragment)
    _atomic_write(args.gamelist, result)
    print("updated", args.gamelist)


if __name__ == "__main__":
    main()